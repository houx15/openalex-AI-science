nm AS (
  SELECT au.id AS author_id, au.display_name,
         element_at(split(lower(trim(au.display_name)), ' '), -1) AS last,
         substr(lower(trim(au.display_name)), 1, 1) AS init
  FROM authors au JOIN samp s ON s.author_id = au.id
),
small_works AS (
  SELECT id FROM works_core_r20261106a
  WHERE publication_year BETWEEN 2018 AND 2022 AND authors_count <= 50 AND NOT is_xpac
),
co AS (
  SELECT DISTINCT s.author_id, a2.author_id AS co_id
  FROM samp s
  JOIN authorship_long_r20261106a a1 ON a1.author_id = s.author_id
  JOIN small_works w ON w.id = a1.work_id
  JOIN authorship_long_r20261106a a2 ON a2.work_id = a1.work_id AND a2.author_id <> s.author_id
  WHERE a1.publication_year_bin IN ('2018','2019','2020','2021','2022')
    AND a2.publication_year_bin IN ('2018','2019','2020','2021','2022')
),
links AS (
  SELECT DISTINCT arxiv_id, work_id FROM paper_family_r20261106b
  WHERE year(v1_date) IN (2023, 2024) AND work_id IS NOT NULL AND NOT is_xpac AND link_flag IS NULL
),
pa AS (
  SELECT DISTINCT l.arxiv_id, a.author_id
  FROM links l JOIN authorship_long_r20261106a a ON a.work_id = l.work_id
  WHERE a.publication_year_bin IN ('2022','2023','2024','2025','2026') AND a.author_id IS NOT NULL
),
cand_papers AS (
  SELECT DISTINCT co.author_id AS sampled_id, pa.arxiv_id
  FROM co JOIN pa ON pa.author_id = co.co_id
),
pa_names AS (
  SELECT pa.arxiv_id, pa.author_id, au.display_name,
         element_at(split(lower(trim(au.display_name)), ' '), -1) AS last,
         substr(lower(trim(au.display_name)), 1, 1) AS init
  FROM pa JOIN authors au ON au.id = pa.author_id
  WHERE pa.arxiv_id IN (SELECT arxiv_id FROM cand_papers)
)
